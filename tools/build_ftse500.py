"""Builds the FTSE Global All Cap top-500 approximation as a Swift source file.

FTSE doesn't publish constituents for free, so this ranks listed companies by market cap
(companiesmarketcap.com CSV export), keeps FTSE-eligible markets, counts China A-shares at
FTSE's 25% inclusion factor, and looks up each sector on Yahoo Finance.

Usage:
    curl -sL "https://companiesmarketcap.com/?download=csv" -o companies.csv
    python3 tools/build_ftse500.py companies.csv Sources/MarketScreener/UniverseFTSE.swift
"""
import csv
import json
import re
import sys
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor

TARGET = 500

# Russia and frontier markets are not in FTSE Global All Cap.
INELIGIBLE = {"Russia", "Argentina", "Vietnam", "Nigeria", "Kazakhstan", "Ukraine", "Venezuela",
              "Sri Lanka", "Bangladesh", "Kenya", "Morocco", "Oman", "Bahrain", "Jordan", "Lebanon",
              "Mongolia", "Iran", "Cyprus", "Panama"}

COUNTRY_CODES = {
    "United States": "US", "China": "CN", "Japan": "JP", "United Kingdom": "GB", "Canada": "CA",
    "Germany": "DE", "France": "FR", "Switzerland": "CH", "India": "IN", "Taiwan": "TW", "Australia": "AU",
    "Netherlands": "NL", "Brazil": "BR", "Spain": "ES", "Sweden": "SE", "South Korea": "KR", "Ireland": "IE",
    "Italy": "IT", "Hong Kong": "HK", "United Arab Emirates": "AE", "Saudi Arabia": "SA", "Singapore": "SG",
    "Denmark": "DK", "Mexico": "MX", "Belgium": "BE", "Norway": "NO", "Finland": "FI", "Israel": "IL",
    "Thailand": "TH", "Poland": "PL", "Austria": "AT", "Luxembourg": "LU", "Kuwait": "KW",
    "South Africa": "ZA", "Qatar": "QA", "Bermuda": "BM", "Colombia": "CO", "Indonesia": "ID",
    "Malaysia": "MY", "Chile": "CL", "Philippines": "PH", "Turkey": "TR", "Greece": "GR", "Portugal": "PT",
    "Peru": "PE", "Uruguay": "UY", "Czech Republic": "CZ", "Hungary": "HU", "New Zealand": "NZ",
    "Cayman Islands": "KY", "Jersey": "JE", "Guernsey": "GG", "Egypt": "EG", "Iceland": "IS",
    "Romania": "RO", "Pakistan": "PK", "Monaco": "MC", "Bahamas": "BS", "Puerto Rico": "PR",
}

# Thin US OTC lines in the source data, mapped to the home-market listing FTSE uses.
OTC_TO_LOCAL = {
    "TCEHY": "0700.HK", "XIACF": "1810.HK", "GLCNF": "GLEN.L", "KBCSF": "KBC.BR",
    "GMBXF": "GMEXICOB.MX", "WMMVF": "WALMEX.MX",
}

SECTORS = {
    "Technology": "Technology", "Financial Services": "Financials", "Healthcare": "Health Care",
    "Consumer Cyclical": "Consumer Disc.", "Consumer Defensive": "Consumer Staples",
    "Communication Services": "Communication", "Industrials": "Industrials", "Energy": "Energy",
    "Basic Materials": "Materials", "Real Estate": "Real Estate", "Utilities": "Utilities",
}


def lookup(symbol):
    """Returns the Yahoo sector for an equity symbol, or None if Yahoo doesn't know it."""
    url = "https://query1.finance.yahoo.com/v1/finance/search?" + urllib.parse.urlencode(
        {"q": symbol, "quotesCount": 3, "newsCount": 0})
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            quotes = json.load(r).get("quotes") or []
    except Exception:
        return None
    for q in quotes:
        if q.get("symbol") == symbol and q.get("quoteType") == "EQUITY":
            return SECTORS.get(q.get("sectorDisp") or q.get("sector"), "Other")
    return None


def main(csv_path, out_path):
    rows = []
    for r in csv.DictReader(open(csv_path, newline="", encoding="utf-8")):
        if r["country"] in INELIGIBLE or r["country"] not in COUNTRY_CODES:
            continue
        try:
            cap = float(r["marketcap"])
        except ValueError:
            continue
        symbol = OTC_TO_LOCAL.get(r["Symbol"].strip(), r["Symbol"].strip())
        if not re.fullmatch(r"[A-Z0-9.\-]+", symbol):
            continue
        weight = cap * (0.25 if symbol.endswith((".SS", ".SZ")) else 1.0)
        name = re.sub(r"\s*\(.*?\)", "", r["Name"]).strip()
        rows.append((weight, symbol, name, COUNTRY_CODES[r["country"]]))
    rows.sort(reverse=True)

    candidates = rows[: TARGET + 150]
    with ThreadPoolExecutor(8) as pool:
        sectors = list(pool.map(lambda row: lookup(row[1]), candidates))

    picked = [(row, s) for row, s in zip(candidates, sectors) if s is not None][:TARGET]
    print(f"{len(picked)} instruments ({sum(s is None for s in sectors)} candidates unknown to Yahoo)", file=sys.stderr)

    def lit(s):
        return json.dumps(s, ensure_ascii=False)

    lines = [
        "// Generated by tools/build_ftse500.py. Do not edit by hand; rerun the script instead.",
        "// Approximates the FTSE Global All Cap top 500 by market cap (China A-shares at 25%).",
        "",
        "extension Universe {",
        "    static let ftse500: [Instrument] = [",
    ]
    for (_, symbol, name, country), sector in picked:
        lines.append(f"        .init(symbol: {lit(symbol)}, name: {lit(name)}, country: {lit(country)}, sector: {lit(sector)}),")
    lines += ["    ]", "}", ""]
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])

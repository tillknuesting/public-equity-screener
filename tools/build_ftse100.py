"""Builds the FTSE 100 approximation as a Swift source file.

FTSE Russell doesn't publish constituents for free, so this takes a pool of London large caps,
checks each on Yahoo Finance, and keeps the 100 largest by market cap (which is how the index
is formed, give or take free-float and eligibility rules).

Usage:
    python3 tools/build_ftse100.py Sources/MarketScreener/UniverseFTSE100.swift
"""
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor

TARGET = 100

# London large caps (Yahoo tickers without the .L suffix; trailing dots are part of the ticker).
CANDIDATES = """
AZN SHEL HSBA ULVR RIO REL BP. GSK BATS LSEG DGE RR. BARC NG. LLOY NWG GLEN AAL CPG BA. TSCO HLN PRU III
STAN EXPN IMB VOD SSE LGEN AV. ABF AHT BT-A CCH CNA CRDA DCC ENT FRES HLMA HIK IHG INF ITRK JD. KGF LAND
MKS MNDI NXT PSH PSN PSON RKT RMV RTO SBRY SDR SGE SGRO SMIN SMT SN. SPX SVT UU. WEIR WTB AUTO ADM ANTO
BEZ BKG BNZL BRBY DPLM EZJ FCIT GAW HWDN ICG IMI LMP MNG MRO PCT PHNX RS1 STJ TW. UTG WPP BAB IAG AAF
ABDN ALW BLND FRAS BTRW CTEC BME ITV HSX JMAT SMDS ROR INVP IGG EDV WISE HL. CCL HBR IWG VTY TPK BWY
""".split()

SECTORS = {
    "Technology": "Technology", "Financial Services": "Financials", "Healthcare": "Health Care",
    "Consumer Cyclical": "Consumer Disc.", "Consumer Defensive": "Consumer Staples",
    "Communication Services": "Communication", "Industrials": "Industrials", "Energy": "Energy",
    "Basic Materials": "Materials", "Real Estate": "Real Estate", "Utilities": "Utilities",
}

UA = {"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"}


def get_json(url):
    for attempt in range(3):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=20) as r:
                return json.load(r)
        except Exception:
            time.sleep(0.8 * (attempt + 1))
    return None


def lookup(ticker):
    """Returns (symbol, name, sector, market cap in GBP) or None if Yahoo doesn't know it."""
    symbol = ticker.rstrip(".") + ".L"   # "BP." trades as BP.L on Yahoo
    search = get_json("https://query1.finance.yahoo.com/v1/finance/search?"
                      + urllib.parse.urlencode({"q": symbol, "quotesCount": 3, "newsCount": 0}))
    quote = next((q for q in (search or {}).get("quotes", [])
                  if q.get("symbol") == symbol and q.get("quoteType") == "EQUITY"), None)
    if quote is None:
        return None
    now = int(time.time())
    ts = get_json(f"https://query1.finance.yahoo.com/ws/fundamentals-timeseries/v1/finance/timeseries/"
                  f"{urllib.parse.quote(symbol)}?type=trailingMarketCap&period1={now - 400 * 86400}&period2={now + 86400}")
    cap = None
    for result in (ts or {}).get("timeseries", {}).get("result", []) or []:
        points = [p for p in (result.get("trailingMarketCap") or []) if p]
        if points:
            cap = points[-1]["reportedValue"]["raw"]
    if not cap:
        return None
    name = quote.get("longname") or quote.get("shortname") or ticker
    name = re.sub(r"\s+(PLC|plc|Plc|p\.l\.c\.|Limited|Ltd\.?)$", "", name.strip())
    sector = SECTORS.get(quote.get("sectorDisp") or quote.get("sector"), "Other")
    return symbol, name, sector, cap


def main(out_path):
    unique = list(dict.fromkeys(CANDIDATES))
    with ThreadPoolExecutor(6) as pool:
        found = [r for r in pool.map(lookup, unique) if r]
    found.sort(key=lambda r: r[3], reverse=True)
    picked = found[:TARGET]
    print(f"{len(found)} of {len(unique)} candidates found; keeping {len(picked)}", file=sys.stderr)

    lines = [
        "// Generated by tools/build_ftse100.py. Do not edit by hand; rerun the script instead.",
        "// Approximates the FTSE 100: the 100 largest London listings by market cap.",
        "",
        "extension Universe {",
        "    static let ftse100: [Instrument] = [",
    ]
    for symbol, name, sector, _ in picked:
        lines.append(f"        .init(symbol: {json.dumps(symbol)}, name: {json.dumps(name, ensure_ascii=False)}, "
                     f"country: \"GB\", sector: {json.dumps(sector)}),")
    lines += ["    ]", "}", ""]
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
